// Exports every component (with its own live demos), the chart types and the Pro component list to the
// kit's style guide (../onlynify-ui/docs/catalog.json), so http://localhost:3500 shows exactly what this site
// shows on /docs/components/<slug> and /pro. Run by `npm run sync` (Node strips the TypeScript types).
// Component demos are free MIT kit markup. Pro entries are metadata only: Pro source never leaves this site.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CHART_TYPES } from "../src/lib/catalog.ts";
import { COMPONENT_DOCS } from "../src/lib/registry.ts";
import { PRO_COMPONENTS } from "../src/lib/pro-components.ts";

export type StyleguideComponent = { slug: string; name: string; page: string; group: string; description: string; isNew?: boolean; demos: { title: string; html: string }[]; pro: string[] };
export type StyleguidePro = { slug: string; title: string; category: string; tier: "pro" | "team"; components: string[]; description: string; height: number };
export type StyleguideCatalog = { note: string; components: StyleguideComponent[]; charts: string[]; pro: StyleguidePro[] };

export function buildStyleguideCatalog(): StyleguideCatalog {
  const pro: StyleguidePro[] = PRO_COMPONENTS.map(({ slug, title, category, tier, components, description, height }) => ({ slug, title, category, tier, components, description, height }));
  const components: StyleguideComponent[] = COMPONENT_DOCS.map((c) => ({
    slug: c.slug,
    name: c.name,
    page: c.page,
    group: c.group,
    description: c.description,
    ...(c.isNew ? { isNew: true } : {}),
    demos: c.demos.map((d) => ({ title: d.title, html: d.html })),
    pro: pro.filter((p) => p.components.includes(c.name)).map((p) => p.slug),
  }));
  return { note: "Generated by onlynify-ui-site/scripts/export-styleguide-catalog.ts (npm run sync). Do not edit by hand.", components, charts: [...CHART_TYPES], pro };
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = buildStyleguideCatalog();
  writeFileSync(join(here, "../../onlynify-ui/docs/catalog.json"), JSON.stringify(data, null, 2) + "\n");
  console.log(`styleguide catalog → onlynify-ui/docs/catalog.json — ${data.components.length} components (${data.components.reduce((n, c) => n + c.demos.length, 0)} demos), ${data.charts.length} chart types, ${data.pro.length} Pro`);
}
